export function reviseNpcDialogue(text: string): string {
  const renamed = text
    .replaceAll('陆川', '陆守义')
    .replaceAll('陆满', '陆建军')
    .replaceAll('小满', '建军')
    .replaceAll(
      '我把旧手机里的聊天也导进电脑了。你慢慢看。',
      '你妈建的“陆家小院”还在，往上翻翻。你小时候也没少在里头说话。',
    );
  return revisions[renamed] || renamed;
}
